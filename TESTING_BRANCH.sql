--2. CHECKING FOR DUPLICATES 
SELECT 
BRANCH_KEY,
COUNT(*) AS ROW_COUNT
FROM MWS.MWS_FB_BRANCH_DIM
GROUP BY BRANCH_KEY
HAVING COUNT(*) > 1; --0 
--3. CHECKING FOR NULLS 
SELECT *
FROM MWS.MWS_FB_BRANCH_DIM
WHERE BRANCH_KEY IS NULL
   OR TRIM(BRANCH_CODE) IS NULL
   OR TRIM(BRANCH_NAME) IS NULL;--0 
--4.CHECKING FOR THE UNKNOWN 
	SELECT *
FROM MWS.MWS_FB_BRANCH_DIM
WHERE BRANCH_KEY = -1;

--5.CHECKING IS ACTIVE 
SELECT *
FROM MWS.MWS_FB_BRANCH_DIM
WHERE IS_ACTIVE IS NULL
   OR IS_ACTIVE NOT IN (0, 1);--0 
   
--6. CHECKING AUDIT COLUMNS 
SELECT *
FROM MWS.MWS_FB_BRANCH_DIM
